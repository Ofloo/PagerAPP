package io.ofloo.pagerapp.shared

import java.io.ByteArrayOutputStream

/**
 * Encodes and decodes a contact invitation as a QR payload.
 *
 * Format: `pagerapp://contact?u=<channel>&s=<server>&n=<name>&i=<sender-id>` — values
 * percent-encoded. `u` is the channel mailbox the inviter offers (never their private mailbox),
 * `i` is the inviter's per-channel sender id. `n` and `i` may be omitted.
 *
 * Decoding also accepts a bare UUID, so a UUID can be pasted instead of scanned.
 */
object ContactQr {

    private const val PREFIX = "pagerapp://contact"

    fun encode(contact: Contact): String {
        val parts = mutableListOf<String>()
        // u1 is the inviter's own receiving mailbox ("write here to reach me"); u2 is the mailbox
        // the inviter prepared for the scanner to receive on, so the scanner has to do nothing.
        parts += "u1=" + enc(contact.receiveOn.ifBlank { contact.uuid })
        if (contact.sendTo.isNotBlank()) parts += "u2=" + enc(contact.sendTo)
        parts += "s=" + enc(contact.serverUrl)
        if (contact.name.isNotBlank()) parts += "n=" + enc(contact.name)
        if (contact.mySenderId.isNotBlank()) parts += "i=" + enc(contact.mySenderId)
        return "$PREFIX?${parts.joinToString("&")}"
    }

    /**
     * Parses [text] into a [Contact]. [mySenderId] is this device's own id for the new channel
     * (generated by the caller). Returns null when there is no usable UUID.
     */
    fun decode(
        text: String,
        fallbackServer: String,
        fallbackName: String? = null,
        mySenderId: String = "",
    ): Contact? {
        val trimmed = text.trim()
        if (trimmed.isEmpty()) return null

        if (!trimmed.startsWith(PREFIX)) {
            val bare = trimmed.trimEnd('/').substringAfterLast('/')
            if (bare.isBlank()) return null
            return Contact(
                name = fallbackName.orEmpty(),
                serverUrl = fallbackServer,
                uuid = bare,
                mySenderId = mySenderId,
            )
        }

        val query = trimmed.substringAfter('?', "")
        val params = query.split('&').mapNotNull { pair ->
            val i = pair.indexOf('=')
            if (i <= 0) null else dec(pair.substring(0, i)) to dec(pair.substring(i + 1))
        }.toMap()

        val u1 = (params["u1"] ?: params["u"])?.trim().orEmpty()
        if (u1.isBlank()) return null
        val u2 = params["u2"]?.trim().orEmpty()
        val server = params["s"]?.trim().takeUnless { it.isNullOrBlank() } ?: fallbackServer
        val name = params["n"]?.trim().takeUnless { it.isNullOrBlank() } ?: fallbackName.orEmpty()
        val peerSender = params["i"]?.trim().orEmpty()

        return if (u2.isNotBlank()) {
            // Two-mailbox invite: we write to u1 and read on u2, which the inviter prepared for us.
            Contact(
                name = name,
                serverUrl = server,
                uuid = u1,
                senderId = peerSender,
                mySenderId = mySenderId,
                sendTo = u1,
                receiveOn = u2,
            )
        } else {
            // Legacy invite: one shared mailbox both ways.
            Contact(
                name = name,
                serverUrl = server,
                uuid = u1,
                senderId = peerSender,
                mySenderId = mySenderId,
            )
        }
    }

    private fun enc(s: String): String = buildString {
        for (b in s.toByteArray(Charsets.UTF_8)) {
            val c = b.toInt() and 0xFF
            val unreserved = c in 'A'.code..'Z'.code || c in 'a'.code..'z'.code ||
                c in '0'.code..'9'.code || c == '-'.code || c == '_'.code ||
                c == '.'.code || c == '~'.code
            if (unreserved) append(c.toChar()) else append('%').append("%02X".format(c))
        }
    }

    private fun dec(s: String): String {
        val out = ByteArrayOutputStream()
        var i = 0
        while (i < s.length) {
            val c = s[i]
            if (c == '%' && i + 3 <= s.length) {
                val hex = s.substring(i + 1, i + 3).toIntOrNull(16)
                if (hex == null) { out.write(c.code); i++ } else { out.write(hex); i += 3 }
            } else {
                out.write(c.code); i++
            }
        }
        return out.toString("UTF-8")
    }
}
